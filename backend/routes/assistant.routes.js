/**
 * EmoLyrics AI Assistant Routes
 * Conversational endpoint connecting users to NLP emotions, recommendations,
 * song searches, and smart playlist generation.
 */

const express = require("express");
const aiAssistantService = require("../services/aiAssistantService");
const playlistGeneratorService = require("../services/playlistGeneratorService");
const { optionalJWT } = require("../middleware/auth.middleware");

const router = express.Router();

/**
 * POST /api/assistant/chat
 * Send a message to the AI Music Assistant (Supports SSE real-time streaming and JSON fallback)
 */
router.post("/chat", optionalJWT, async (req, res, next) => {
  try {
    let rawMessage = null;
    let sessionId = null;
    let wantsStream = false;

    if (typeof req.body === "string") {
      rawMessage = req.body;
    } else if (req.body && typeof req.body === "object") {
      rawMessage = req.body.message ?? req.body.query ?? req.body.prompt ?? req.body.text;
      sessionId = req.body.sessionId;
      if (req.body.stream !== undefined) {
        wantsStream = Boolean(req.body.stream);
      }
    }

    // Check Accept header for event-stream unless explicitly disabled via stream: false
    if (req.headers.accept && req.headers.accept.includes("text/event-stream")) {
      wantsStream = req.body?.stream !== false;
    }

    if (rawMessage === undefined || rawMessage === null) {
      return res.status(400).json({
        success: false,
        message: "Message string is required."
      });
    }

    const message = typeof rawMessage === "string" ? rawMessage.trim() : String(rawMessage).trim();

    if (!message) {
      return res.status(400).json({
        success: false,
        message: "A non-empty message is required to chat with the assistant."
      });
    }

    const effectiveSessionId = sessionId || "guest-session-" + Date.now();
    const userId = req.user ? req.user._id : null;

    // Real-time streaming response using SSE
    if (wantsStream) {
      return aiAssistantService.streamUserMessage({
        message,
        sessionId: effectiveSessionId,
        userId,
        req,
        res
      });
    }

    // Traditional non-streaming fallback for compatibility
    const result = await aiAssistantService.processUserMessage({
      message,
      sessionId: effectiveSessionId,
      userId
    });

    return res.json({
      success: true,
      reply: result.reply || result.message || "",
      message: result.message || result.reply || "",
      ...result
    });
  } catch (error) {
    next(error);
  }
});

/**
 * GET /api/assistant/history
 * Fetch conversation history for a given session
 */
router.get("/history", optionalJWT, async (req, res, next) => {
  try {
    const { sessionId, limit = 50 } = req.query;

    if (!sessionId) {
      return res.status(400).json({
        success: false,
        message: "sessionId query parameter is required."
      });
    }

    const messages = await aiAssistantService.getSessionHistory(
      sessionId,
      parseInt(limit, 10) || 50
    );

    return res.json({
      success: true,
      sessionId,
      messages
    });
  } catch (error) {
    next(error);
  }
});

/**
 * POST /api/assistant/clear
 * Clear conversational history for this session
 */
router.post("/clear", optionalJWT, async (req, res, next) => {
  try {
    const { sessionId } = req.body;

    if (!sessionId) {
      return res.status(400).json({
        success: false,
        message: "sessionId is required."
      });
    }

    await aiAssistantService.clearSessionHistory(sessionId);

    return res.json({
      success: true,
      message: "Chat history cleared successfully."
    });
  } catch (error) {
    next(error);
  }
});

/**
 * POST /api/assistant/save-playlist
 * One-click action to save a playlist draft generated by the assistant
 */
router.post("/save-playlist", optionalJWT, async (req, res, next) => {
  try {
    const { playlist } = req.body;
    const userId = req.user ? req.user._id : null;

    if (!playlist || !playlist.title || !playlist.songs) {
      return res.status(400).json({
        success: false,
        message: "Valid playlist draft object is required."
      });
    }

    const saved = await playlistGeneratorService.savePlaylist(playlist, userId);
    return res.status(201).json({
      success: true,
      message: `Playlist "${saved.title}" saved successfully!`,
      playlist: saved
    });
  } catch (error) {
    next(error);
  }
});

module.exports = router;

